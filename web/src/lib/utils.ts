import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';
import { formatNumber, i18n, t } from '#lib/i18n/index.svelte.ts';

export function cn(...inputs: ClassValue[]) {
	return twMerge(clsx(inputs));
}

const BYTE_UNITS = {
	en: ['B', 'KB', 'MB', 'GB', 'TB'],
	fr: ['o', 'Ko', 'Mo', 'Go', 'To']
};

export function formatBytes(bytes: number): string {
	const units = BYTE_UNITS[i18n.locale];
	if (!bytes || bytes < 0) return `0 ${units[0]}`;
	let i = 0;
	let n = bytes;
	while (n >= 1024 && i < units.length - 1) {
		n /= 1024;
		i++;
	}
	return `${formatNumber(n < 10 ? n : Math.round(n), { maximumFractionDigits: 1 })} ${units[i]}`;
}

export function formatDuration(seconds?: number): string {
	if (!seconds || seconds < 0) return '–';
	const s = Math.round(seconds);
	const h = Math.floor(s / 3600);
	const m = Math.floor((s % 3600) / 60);
	const sec = s % 60;
	if (h > 0) return `${h}:${m.toString().padStart(2, '0')}:${sec.toString().padStart(2, '0')}`;
	return `${m}:${sec.toString().padStart(2, '0')}`;
}

// Grid separator label (Today / Yesterday / This week / This month / "Month YYYY"),
// compared on local midnight.
export function dateGroupLabel(unixSeconds: number): string {
	const d = new Date(unixSeconds * 1000);
	const now = new Date();
	const startOfDay = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
	const dayMs = 86_400_000;
	const diffDays = Math.floor((startOfDay(now) - startOfDay(d)) / dayMs);

	if (diffDays <= 0) return t('date.today');
	if (diffDays === 1) return t('date.yesterday');
	if (diffDays < 7) return t('date.thisWeek');
	if (d.getFullYear() === now.getFullYear() && d.getMonth() === now.getMonth()) return t('date.thisMonth');
	return d.toLocaleDateString(i18n.tag, { month: 'long', year: 'numeric' });
}

type TagLike = { slug: string; name: string; auto?: boolean };

export type TagKind =
	| 'allstar'
	| 'source'
	| 'resolution'
	| 'fps'
	| 'codec'
	| 'user';

const RESOLUTION_SLUGS = new Set(['480p', '720p', '1080p', '1440p', '2160p', '4k', '8k']);
const CODEC_SLUGS = new Set(['h264', 'h265', 'hevc', 'av1', 'vp9', 'mpeg4', 'prores']);
const SOURCE_SLUGS = new Set(['obs', 'shadowplay']);

export function tagKind(t: TagLike): TagKind {
	const slug = (t.slug || '').toLowerCase();
	if (slug === 'allstar') return 'allstar';
	if (SOURCE_SLUGS.has(slug)) return 'source';
	if (RESOLUTION_SLUGS.has(slug) || /^\d+x\d+$/.test(slug)) return 'resolution';
	if (/^\d+fps$/.test(slug)) return 'fps';
	if (CODEC_SLUGS.has(slug)) return 'codec';
	return 'user';
}

export function formatDateRelative(unix: number): string {
	if (!unix) return '';
	const now = Date.now() / 1000;
	const diff = now - unix;
	if (diff < 60) return t('date.justNow');
	if (diff < 3600) return t('date.minutesAgo', { count: Math.floor(diff / 60) });
	if (diff < 86400) return t('date.hoursAgo', { count: Math.floor(diff / 3600) });
	if (diff < 604800) return t('date.daysAgo', { count: Math.floor(diff / 86400) });
	const d = new Date(unix * 1000);
	return d.toLocaleDateString(i18n.tag, { day: '2-digit', month: 'short', year: 'numeric' });
}

// Folder names where ":" was replaced by two spaces
// ("Counter-strike  Global Offensive"): shown with a single space.
export function gameName(name?: string): string {
	return (name ?? '').replace(/\s{2,}/g, ' ').trim();
}

export function formatDateTime(unix: number): string {
	return new Date(unix * 1000).toLocaleString(i18n.tag, {
		day: 'numeric',
		month: 'short',
		year: 'numeric',
		hour: '2-digit',
		minute: '2-digit'
	});
}

// OBS: "Replay 2025-12-30 21-46-38". ShadowPlay: "<Game> 2019.11.23 - 23.09.56.04(.DVR)".
const OBS_NAME = /^(replay|recording|clip)?\s*(\d{4})-(\d{2})-(\d{2})[ _](\d{2})-(\d{2})-(\d{2})$/i;
const SHADOWPLAY_NAME = /^(.*?)\s*(\d{4})\.(\d{2})\.(\d{2}) - (\d{2})\.(\d{2})\.(\d{2})(?:\.\d+)*(?:\.DVR)?$/i;

// True when the name is only a timestamp generated by the recorder.
export function isAutoName(name: string): boolean {
	return OBS_NAME.test(name.trim()) || SHADOWPLAY_NAME.test(name.trim());
}

// Readable title: a hand-typed name stays as is, a recorder timestamp becomes
// "Replay from Dec 30, 2025, 09:46 PM" (short: "Dec 30, 2025, 09:46 PM", for
// narrow cards).
export function clipTitle(clip: { name: string; mtime: number }, short = false): string {
	const n = clip.name.trim();
	const m = OBS_NAME.exec(n) ?? SHADOWPLAY_NAME.exec(n);
	if (!m) return n;
	const [, , y, mo, d, h, mi] = m;
	const date = new Date(+y, +mo - 1, +d, +h, +mi);
	if (Number.isNaN(date.getTime())) return n;
	const day = date.toLocaleDateString(i18n.tag, { day: 'numeric', month: 'short', year: 'numeric' });
	const time = date.toLocaleTimeString(i18n.tag, { hour: '2-digit', minute: '2-digit' });
	if (short) return t('clipTitle.short', { day, time });
	return t(OBS_NAME.test(n) ? 'clipTitle.replay' : 'clipTitle.clip', { day, time });
}

export function formatTotalDuration(seconds: number): string {
	if (!seconds || seconds < 60) return `${Math.round(seconds || 0)} s`;
	const h = Math.floor(seconds / 3600);
	const m = Math.round((seconds % 3600) / 60);
	return h > 0 ? `${h} h ${m.toString().padStart(2, '0')}` : `${m} min`;
}

// Technical tags (resolution, fps, codec, source): set by the scan, shown as
// metadata, never offered for editing.
export function isTechTag(t: TagLike): boolean {
	const k = tagKind(t);
	return k === 'resolution' || k === 'fps' || k === 'codec' || k === 'source';
}

// Tag chip color by kind, taken from the first version: each family keeps its
// hue everywhere (card, clip, Tags page).
export function tagChipClass(t: TagLike): string {
	switch (tagKind(t)) {
		case 'allstar':
			return 'bg-amber-500/15 text-amber-300 ring-amber-500/30';
		case 'source':
			return 'bg-sky-500/15 text-sky-300 ring-sky-500/30';
		case 'resolution':
			return 'bg-purple-500/15 text-purple-300 ring-purple-500/30';
		case 'fps':
			return 'bg-rose-500/15 text-rose-300 ring-rose-500/30';
		case 'codec':
			return 'bg-cyan-500/15 text-cyan-300 ring-cyan-500/30';
		default:
			return 'bg-primary/15 text-primary ring-primary/30';
	}
}
